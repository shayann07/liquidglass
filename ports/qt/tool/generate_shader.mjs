/** Apache-2.0. Generate Qt Quick's shaders from the production SkSL; never a second implementation.
 *
 *   node tool/generate_shader.mjs           write LiquidGlass/shaders/liquidglass.{vert,frag} and LiquidGlass/GlassEffect.qml
 *   node tool/generate_shader.mjs --check   fail if any is stale
 *
 * The source is ports/skia/shaders/material.sksl, the export of the Compose library's material shader.
 * Qt Quick's ShaderEffect takes Vulkan-style GLSL 440, compiled to .qsb by qsb (CI does that on Linux).
 * Every uniform lives in one std140 block at binding 0 that begins with qt_Matrix and qt_Opacity, and
 * the ShaderEffect fills the block's other members from its QML properties of the same names. So:
 *
 * - SkSL types become GLSL types, as for Flutter (ports/flutter/tool/generate_shader.mjs);
 * - the material's `uniform` declarations move into the block, and GlassEffect.qml declares one QML
 *   property per member with the matching type (real, point, vector3d, vector4d);
 * - `content.eval(p)` reads `source`, the live backdrop under the padded glass (a ShaderEffectSource
 *   whose sourceRect is that region), at the padded layer's pixel p; `field.eval(p)` reads `field`;
 * - `main(coord)` becomes `glassMain(coord)`, called with the padded layer's pixel
 *   (qt_TexCoord0 × uLayerSize).
 *
 * `wideAt`, the wide tone kernel, is replaced as for Flutter: thirteen taps of a Gaussian with the
 * kernel's sigma instead of a quarter-scale blurred copy. It sets tone only, never detail.
 */
import {readFile, writeFile, mkdir} from 'node:fs/promises';

const here = path => new URL(path, import.meta.url);
const source = (await readFile(here('../../skia/shaders/material.sksl'), 'utf8')).replace(/\r\n/g, '\n');

function replaceOnce(text, pattern, replacement, what) {
  const matches = text.match(new RegExp(pattern.source, pattern.flags.includes('g') ? pattern.flags : pattern.flags + 'g'));
  if (!matches || matches.length !== 1) throw new Error(`Shader contract changed: ${what} (${matches?.length ?? 0} matches)`);
  return text.replace(pattern, replacement);
}

let body = source;
body = replaceOnce(body, /^uniform shader content;.*\n/m, '', 'the content child');
body = replaceOnce(body, /^uniform shader field;.*\n/m, '', 'the field child');
body = replaceOnce(body, /half3 wideAt\(float2 p\) \{\n(?:.*\n)*?\}\n/m, `half3 wideAt(float2 p) {
    // Qt: thirteen taps of a Gaussian with the wide kernel's sigma (see generate_shader.mjs).
    float s = max(uWideKernel, 1.0);
    half3 sum = backdropAt(p);
    float w1 = 0.6065, w2 = 0.1353;
    for (int i = 0; i < 6; i++) {
        float a = float(i) * 1.0471976;
        float b = a + 0.5235988;
        sum += backdropAt(p + float2(cos(a), sin(a)) * s) * half(w1);
        sum += backdropAt(p + float2(cos(b), sin(b)) * (2.0 * s)) * half(w2);
    }
    return sum / half(1.0 + 6.0 * (w1 + w2));
}
`, 'wideAt');
body = body.replace(/\bcontent\.eval\(/g, 'sampleInput(').replace(/\bfield\.eval\(/g, 'sampleField(');
if (/\b(content|field)\.eval\b/.test(body) || /\buniform shader\b/.test(body)) throw new Error('Unhandled shader child');
body = replaceOnce(body, /^half4 main\(float2 coord\) \{/m, 'half4 glassMain(float2 coord) {', 'main');
const types = [['float2x2', 'mat2'], ['float3x3', 'mat3'], ['half4', 'vec4'], ['half3', 'vec3'], ['half2', 'vec2'],
  ['half', 'float'], ['float4', 'vec4'], ['float3', 'vec3'], ['float2', 'vec2']];
for (const [from, to] of types) body = body.replace(new RegExp(`\\b${from}\\b`, 'g'), to);

// The material's uniforms, in declaration order, become block members.
const uniforms = [...body.matchAll(/^uniform\s+(float|vec2|vec3|vec4)\s+(\w+)\s*;.*$/gm)]
  .map(([, type, name]) => ({type, name}));
if (uniforms.length < 60) throw new Error(`Expected the material's uniforms, found ${uniforms.length}`);
body = body.replace(/^uniform\s+(float|vec2|vec3|vec4)\s+(\w+)\s*;.*\n/gm, '');
if (/^uniform\b/m.test(body)) throw new Error('A uniform of an unhandled type remains');

const block = `layout(std140, binding = 0) uniform buf {
    mat4 qt_Matrix;
    float qt_Opacity;
    vec2 uLayerSize;   // the padded layer (the ShaderEffect item), device px
    vec2 uFieldSize;   // the distance field texture's size, px (unused while the shape is analytic)
${uniforms.map(u => `    ${u.type} ${u.name};`).join('\n')}
};`;

const header = `// Apache-2.0. Generated by ports/qt/tool/generate_shader.mjs from ports/skia/shaders/material.sksl.
// Do not edit: \`node tool/generate_shader.mjs --check\` fails when this drifts from the source.
#version 440
`;

const vert = `${header}
layout(location = 0) in vec4 qt_Vertex;
layout(location = 1) in vec2 qt_MultiTexCoord0;
layout(location = 0) out vec2 qt_TexCoord0;

${block}

void main() {
    qt_TexCoord0 = qt_MultiTexCoord0;
    gl_Position = qt_Matrix * qt_Vertex;
}
`;

const frag = `${header}
layout(location = 0) in vec2 qt_TexCoord0;
layout(location = 0) out vec4 fragColor;

${block}

layout(binding = 1) uniform sampler2D source;  // the live backdrop under the padded layer
layout(binding = 2) uniform sampler2D field;   // the sampled distance field

vec4 sampleInput(vec2 p) {
    return texture(source, p / uLayerSize);
}

vec4 sampleField(vec2 p) {
    return texture(field, p / uFieldSize);
}

${body.trimEnd()}

void main() {
    fragColor = glassMain(qt_TexCoord0 * uLayerSize) * qt_Opacity;
}
`;

const qmlType = {float: 'real', vec2: 'point', vec3: 'vector3d', vec4: 'vector4d'};
const qmlValue = {
  float: v => `v[0]`,
  vec2: v => `Qt.point(v[0], v[1])`,
  vec3: v => `Qt.vector3d(v[0], v[1], v[2])`,
  vec4: v => `Qt.vector4d(v[0], v[1], v[2], v[3])`,
};
const qml = `// Apache-2.0. Generated by ports/qt/tool/generate_shader.mjs; do not edit.
// The ShaderEffect running the material: one property per member of the shaders' uniform block.
// GlassSurface.qml sets them all through setUniforms(Material.uniforms(...)).
import QtQuick

ShaderEffect {
    vertexShader: "shaders/liquidglass.vert.qsb"
    fragmentShader: "shaders/liquidglass.frag.qsb"

    property var source
    property var field
    property point uLayerSize
    property point uFieldSize: Qt.point(1, 1)
${uniforms.map(u => `    property ${qmlType[u.type]} ${u.name}`).join('\n')}

    /** Sets every material uniform from {name: [numbers]} (material.js). */
    function setUniforms(values) {
        let v
${uniforms.map(u => `        v = values.${u.name}; if (v) ${u.name} = ${qmlValue[u.type]('v')}`).join('\n')}
    }
}
`;

const outputs = [
  ['../LiquidGlass/shaders/liquidglass.vert', vert],
  ['../LiquidGlass/shaders/liquidglass.frag', frag],
  ['../LiquidGlass/GlassEffect.qml', qml],
];
if (process.argv.includes('--check')) {
  const stale = [];
  for (const [path, text] of outputs) {
    const actual = await readFile(here(path), 'utf8').catch(() => null);
    if (actual?.replace(/\r\n/g, '\n') !== text) stale.push(path);
  }
  if (stale.length) throw new Error(`Generated files are stale (${stale.join(', ')}). Run node tool/generate_shader.mjs.`);
  console.log(`liquidglass.vert, liquidglass.frag and GlassEffect.qml match material.sksl (${uniforms.length} uniforms).`);
} else {
  for (const [path, text] of outputs) {
    await mkdir(new URL('.', here(path)), {recursive: true});
    await writeFile(here(path), text);
  }
  console.log(`Generated the Qt shaders and GlassEffect.qml (${uniforms.length} material uniforms).`);
}
